#!/usr/bin/env python3
"""Writes archipelago/fsotp/location_data.py: the chests that are Archipelago
locations (the ones the port's randomizer shuffles, minus table entries that
have no chest in the game), with the names Archipelago's A Link to the Past
world uses for them.

    python3 archipelago/tools/gen_locations.py zelda3.sfc path/to/worlds/alttp/Regions.py

The ROM is only read for the chest table (room, item); nothing of it is copied
but which item the original game has in which chest. Regions.py comes from
https://raw.githubusercontent.com/ArchipelagoMW/Archipelago/main/worlds/alttp/Regions.py
"""
import re
import sys

CHEST_TABLE = 0xE96E  # LoROM address of the chest table (3 bytes a chest: room word, item)
NUM_CHESTS = 168
# Chest table entries in rooms without a chest object (ALttP randomizers move
# some of these chests elsewhere; in this game nobody can open them). Must
# match IsDeadChestRoom in src/randomizer.c.
DEAD_ROOMS = {0x005, 0x016, 0x05B, 0x12D, 0x13D}
DUNGEON_ITEMS = {0x24, 0x25, 0x32, 0x33}  # small key, compass, big key, map


def main():
    rom = open(sys.argv[1], 'rb').read()
    if len(rom) & 0x200:
        rom = rom[0x200:]  # copier header
    regions = open(sys.argv[2]).read()
    off = CHEST_TABLE  # $01:E96E, which is file offset 0xE96E in a LoROM
    ent = []
    for i in range(NUM_CHESTS):
        a = off + 3 * i
        w = rom[a] | rom[a + 1] << 8
        ent.append((CHEST_TABLE + 3 * i, w & 0x7FFF, w >> 15, rom[a + 2]))
    names = {}
    for m in re.finditer(r"""^\s*(['"])(.+?)\1:\s*\((0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+)""", regions, re.M):
        names[int(m.group(3), 16)] = m.group(2)
    # The port's chest index: the table sorted by room (stable), as the asset
    # compiler lays it out (assets/compile_resources.py).
    order = sorted(range(NUM_CHESTS), key=lambda i: ent[i][1])
    rows, seen = [], set()
    for idx, ri in enumerate(order):
        addr, room, big, item = ent[ri]
        if room in DEAD_ROOMS or item in DUNGEON_ITEMS:
            continue
        name = names.get(addr)
        if not name:
            raise SystemExit(f'no Archipelago name for chest {idx} (room {room:#x}, {addr:#x})')
        if name in seen:
            raise SystemExit(f'two chests named {name!r}')
        seen.add(name)
        rows.append((idx, room, item, name))
    out = ['# Generated by archipelago/tools/gen_locations.py; do not edit.',
           '# (chest index in the port, room, item code in the original game, name)',
           'CHESTS = [']
    for idx, room, item, name in rows:
        out.append(f'    ({idx}, {room:#05x}, {item:#04x}, {name!r}),')
    out.append(']')
    open('archipelago/fsotp/location_data.py', 'w').write('\n'.join(out) + '\n')
    print(len(rows), 'chests')


if __name__ == '__main__':
    main()
